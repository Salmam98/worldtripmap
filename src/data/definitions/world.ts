const byId = new Map(WORLD_UNITS.map((u) => [u.id, u]));

function note(u: WorldUnit): string | undefined {
  if (u.status === 'un-observer') return 'UN observer state';
  if (u.status !== 'territory') return undefined;
  const sovereign = u.sovereign ? byId.get(u.sovereign)?.name : undefined;
  return sovereign ?? 'Other area';
}


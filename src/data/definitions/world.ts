/**
 * World map: countries and territories.
 *
 * Counting rule (also explained on the site): the headline total is 195, the 193 member states of
 * the United Nations plus its two permanent observer states, the Holy See and the State of
 * Palestine. Every other area in the dataset that has its own ISO 3166-1 code (Greenland, Hong
 * Kong, Puerto Rico and so on) can be marked, and is counted separately as a territory.
 *
 * `ne` lists the Natural Earth ADM0_A3 features merged into each unit by scripts/geo/build-geo.ts.
 * Areas without an ISO code are merged into the UN member state they are part of for UN purposes
 * (Somaliland into Somalia, Northern Cyprus into Cyprus). Sources: un.org/en/about-us/member-states
 * and un.org/en/about-us/non-member-states, checked 10 October 2026.
 */

export type WorldStatus = 'un-member' | 'un-observer' | 'territory';


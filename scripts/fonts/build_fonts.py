#!/usr/bin/env python3
"""Build the self-hosted fonts used by WorldTripMap.

Inputs (place in .cache/fonts/, downloaded from https://github.com/google/fonts/tree/main/ofl):
  Manrope-VF.ttf              ofl/manrope/Manrope[wght].ttf
  DMSerifDisplay-Regular.ttf  ofl/dmserifdisplay/DMSerifDisplay-Regular.ttf
  DMSerifDisplay-Italic.ttf   ofl/dmserifdisplay/DMSerifDisplay-Italic.ttf
  Caveat-VF.ttf               ofl/caveat/Caveat[wght].ttf

Outputs:
  src/assets/fonts/ui/*.woff2            site typography (subset, split by unicode-range)
  src/lib/poster/fonts/data/*.ts         poster fonts as base64 WOFF, loaded on demand and
                                         converted to vector outlines by the poster engine

All four families are licensed under the SIL Open Font License 1.1 (see src/assets/fonts/licenses).
Requires: pip install fonttools brotli
"""
from __future__ import annotations

import base64
import io
import sys
from pathlib import Path

from fontTools.subset import Options, Subsetter
from fontTools.ttLib import TTFont
from fontTools.varLib import instancer

ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / ".cache" / "fonts"
UI_OUT = ROOT / "src" / "assets" / "fonts" / "ui"
POSTER_OUT = ROOT / "src" / "lib" / "poster" / "fonts" / "data"

def rng(a: int, b: int) -> list[int]:
    return list(range(a, b + 1))

# Matches the "latin" / "latin-ext" split used by most web font services.
LATIN = (
    rng(0x20, 0x7E) + rng(0xA0, 0xFF) + [0x131, 0x152, 0x153, 0x2BB, 0x2BC, 0x2C6, 0x2DA, 0x2DC]
    + rng(0x2000, 0x206F) + [0x20AC, 0x2122, 0x2191, 0x2193, 0x2212, 0x2215, 0xFEFF, 0xFFFD]
    + [0x2190, 0x2192, 0x00D7, 0x2713]
)
LATIN_EXT = (
    rng(0x100, 0x24F) + rng(0x1E00, 0x1EFF) + rng(0x2C60, 0x2C7F) + rng(0xA720, 0xA7FF)
    + [0x259, 0x1DBC, 0x1DBD, 0x2020, 0x20A0, 0x20AB, 0x20AD, 0x2113]
)
LATIN_EXT = [c for c in LATIN_EXT if c not in set(LATIN)]
GREEK = rng(0x370, 0x3FF)
CYRILLIC = rng(0x400, 0x4FF)
CURRENCY = rng(0x20A0, 0x20BF)

LAYOUT_FEATURES = ["kern", "liga", "mark", "mkmk", "ccmp", "locl"]

def subset(font: TTFont, unicodes: list[int], flavor: str | None) -> bytes:
    opts = Options()
    opts.layout_features = LAYOUT_FEATURES
    opts.hinting = False
    opts.desubroutinize = True
    opts.notdef_outline = True
    opts.name_IDs = [0, 1, 2, 3, 4, 5, 6, 13, 14]
    opts.drop_tables += ["DSIG", "STAT", "MVAR", "meta"] if "fvar" not in font else ["DSIG", "meta"]
    opts.flavor = flavor
    sub = Subsetter(opts)
    sub.populate(unicodes=unicodes)
    sub.subset(font)
    font.flavor = flavor
    buf = io.BytesIO()
    font.save(buf)
    return buf.getvalue()

def open_font(name: str) -> TTFont:
    path = SRC / name
    if not path.exists():
        sys.exit(f"Missing {path}. See the header of this script for where to get it.")
    return TTFont(path)

def reload(font: TTFont) -> TTFont:
    """Round-trip through bytes so lazily loaded tables are consistent before subsetting."""
    buf = io.BytesIO()
    font.save(buf)
    buf.seek(0)
    return TTFont(buf)

def write(path: Path, data: bytes) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(data)
    print(f"{path.relative_to(ROOT)}  {len(data) / 1024:.1f} KB")

def write_ts(name: str, data: bytes, family: str, weight: int, style: str) -> None:
    b64 = base64.b64encode(data).decode("ascii")
    body = (
        "// Generated by scripts/fonts/build_fonts.py. Do not edit by hand.\n"
        f"// {family} {weight} {style}, WOFF, SIL Open Font License 1.1.\n"
        f"export default \"{b64}\";\n"
    )
    path = POSTER_OUT / f"{name}.ts"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(body)
    print(f"{path.relative_to(ROOT)}  {len(data) / 1024:.1f} KB (woff)")

def build_ui() -> None:
    # Manrope: keep the weight axis (300-800) so the site can use any weight from one file.
    for label, unicodes in (("latin", LATIN), ("latinext", LATIN_EXT)):
        vf = open_font("Manrope-VF.ttf")
        vf = reload(instancer.instantiateVariableFont(vf, {"wght": (300, 800)}))
        write(UI_OUT / f"manrope-var-{label}.woff2", subset(vf, unicodes, "woff2"))
    for label, unicodes in (("latin", LATIN), ("latinext", LATIN_EXT)):
        write(UI_OUT / f"dmserifdisplay-400-{label}.woff2",
              subset(open_font("DMSerifDisplay-Regular.ttf"), unicodes, "woff2"))

def build_poster() -> None:
    wide = sorted(set(LATIN + LATIN_EXT + GREEK + CYRILLIC + CURRENCY))
    for weight in (300, 500, 700):
        vf = open_font("Manrope-VF.ttf")
        static = reload(instancer.instantiateVariableFont(vf, {"wght": weight}))
        write_ts(f"manrope-{weight}", subset(static, wide, "woff"), "Manrope", weight, "normal")
    write_ts("dmserif-400", subset(open_font("DMSerifDisplay-Regular.ttf"), wide, "woff"),
             "DM Serif Display", 400, "normal")
    write_ts("dmserif-400i", subset(open_font("DMSerifDisplay-Italic.ttf"), wide, "woff"),
             "DM Serif Display", 400, "italic")
    vf = open_font("Caveat-VF.ttf")
    static = reload(instancer.instantiateVariableFont(vf, {"wght": 600}))
    write_ts("caveat-600", subset(static, wide, "woff"), "Caveat", 600, "normal")

if __name__ == "__main__":
    build_ui()
    build_poster()
